-- Omok database (Supabase). Run it in the SQL Editor; safe to re-run.
-- Row level security is on with no policies: only the server (SUPABASE_SECRET_KEY,
-- which bypasses RLS) reads and writes; the publishable key sees nothing.

CREATE TABLE IF NOT EXISTS leaderboard (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    score INTEGER NOT NULL,
    level INTEGER NOT NULL,
    stones INTEGER NOT NULL,
    date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS game_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moves TEXT NOT NULL,
    winner INTEGER NOT NULL,
    game_mode TEXT,
    level INTEGER,
    stone_count INTEGER,
    date TEXT,
    time TEXT
);

ALTER TABLE leaderboard ENABLE ROW LEVEL SECURITY;
ALTER TABLE game_records ENABLE ROW LEVEL SECURITY;

-- Dashboard statistics in one call (POST /rest/v1/rpc/game_stats), server only
CREATE OR REPLACE FUNCTION game_stats() RETURNS json LANGUAGE sql STABLE AS $$
    SELECT json_build_object(
        'total_games', COUNT(*),
        'player_wins', COUNT(*) FILTER (WHERE winner = 1),
        'ai_wins', COUNT(*) FILTER (WHERE winner = 2),
        'draws', COUNT(*) FILTER (WHERE winner = 0),
        'practice_games', COUNT(*) FILTER (WHERE game_mode = 'practice'),
        'challenge_games', COUNT(*) FILTER (WHERE game_mode = 'challenge'),
        'daily_stats', (
            SELECT COALESCE(json_agg(d ORDER BY d.date DESC), '[]')
            FROM (SELECT date, COUNT(*) AS count, COUNT(*) FILTER (WHERE winner = 1) AS player_wins
                  FROM game_records GROUP BY date ORDER BY date DESC LIMIT 7) d
        )
    ) FROM game_records
$$;
REVOKE EXECUTE ON FUNCTION game_stats() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION game_stats() TO service_role;

